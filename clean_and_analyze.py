"""Clean data/raw_sales.csv, calculate KPIs, write insights and dashboard data."""
import json
import pandas as pd

df = pd.read_csv("data/raw_sales.csv")
raw_rows = len(df)

# ---- Cleaning ----
df = df.drop_duplicates()
dupes_removed = raw_rows - len(df)
missing_segment = int(df["segment"].isna().sum())
df["segment"] = df["segment"].fillna("Unknown")
df["region"] = df["region"].str.strip().str.title()
df["order_date"] = pd.to_datetime(df["order_date"])
df = df[(df["quantity"] > 0) & (df["unit_price"] > 0)]

# ---- Derived columns ----
df["sales"] = (df["quantity"] * df["unit_price"] * (1 - df["discount"])).round(2)
df["profit"] = (df["sales"] - df["quantity"] * df["unit_cost"]).round(2)
df["month"] = df["order_date"].dt.to_period("M").astype(str)
df["year"] = df["order_date"].dt.year
df.to_csv("data/clean_sales.csv", index=False)

# ---- KPIs ----
total_sales, total_profit = df["sales"].sum(), df["profit"].sum()
orders = df["order_id"].nunique()
kpi = {
    "records": int(len(df)), "orders": int(orders),
    "total_sales": round(total_sales, 2), "total_profit": round(total_profit, 2),
    "profit_margin_pct": round(total_profit / total_sales * 100, 2),
    "avg_order_value": round(total_sales / orders, 2),
}

def group(col):
    g = df.groupby(col).agg(sales=("sales", "sum"), profit=("profit", "sum")).round(2)
    g["margin_pct"] = (g["profit"] / g["sales"] * 100).round(2)
    return g.sort_values("sales", ascending=False)

by_cat, by_region, by_seg = group("category"), group("region"), group("segment")
by_month = df.groupby("month").agg(sales=("sales", "sum"), profit=("profit", "sum")).round(2)
by_product = group("product")
top3_share = by_product["sales"].head(3).sum() / total_sales * 100
df["disc_band"] = pd.cut(df["discount"], [-0.01, 0, 0.1, 0.2, 0.3], labels=["0%", "1-10%", "11-20%", "21-30%"])
disc = df.groupby("disc_band", observed=True).agg(sales=("sales", "sum"), profit=("profit", "sum"))
disc["margin_pct"] = (disc["profit"] / disc["sales"] * 100).round(2)
q4 = df[df["order_date"].dt.month.isin([10, 11, 12])]["sales"].sum() / total_sales * 100

# ---- Insights (computed from the data, not typed in) ----
insights = [
    f"Top 3 products ({', '.join(by_product.index[:3])}) generated {top3_share:.1f}% of total sales.",
    f"{by_cat.index[0]} is the highest-selling category ({by_cat['sales'].iloc[0]/total_sales*100:.1f}% of sales) but has a {by_cat.loc[by_cat.index[0], 'margin_pct']}% margin; "
    f"{by_cat['margin_pct'].idxmax()} has the best margin ({by_cat['margin_pct'].max()}%).",
    f"{by_region.index[0]} is the top region by sales ({by_region['sales'].iloc[0]/total_sales*100:.1f}%); {by_region['margin_pct'].idxmin()} has the lowest margin ({by_region['margin_pct'].min()}%).",
    f"Orders with 21-30% discount have a {disc.loc['21-30%', 'margin_pct']}% margin versus {disc.loc['0%', 'margin_pct']}% with no discount.",
    f"October to December contributes {q4:.1f}% of sales, showing a festive-season peak.",
]
with open("insights.md", "w") as f:
    f.write("# Key Insights (auto-generated by clean_and_analyze.py)\n\n")
    f.write("\n".join(f"{i+1}. {t}" for i, t in enumerate(insights)) + "\n")

# ---- Dashboard data ----
def rows(g, key):
    return [{key: k, "sales": float(r.sales), "profit": float(r.profit)} for k, r in g.iterrows()]
data = {"kpi": kpi, "category": rows(by_cat, "name"), "region": rows(by_region, "name"),
        "segment": rows(by_seg, "name"), "month": rows(by_month, "name"),
        "top_products": rows(by_product.head(5), "name"), "insights": insights}
with open("dashboard/data.js", "w") as f:
    f.write("const DASHBOARD_DATA = " + json.dumps(data, indent=1) + ";\n")

print(f"Raw rows: {raw_rows} | duplicates removed: {dupes_removed} | missing segment filled: {missing_segment}")
print(f"Clean records: {kpi['records']}")
print(json.dumps(kpi, indent=1))
print("\n".join(insights))
